import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import readline from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";

const envPath = path.resolve(process.cwd(), ".env.mail");

const required = [
  { key: "MAIL_HOST", label: "SMTP host", required: true },
  { key: "MAIL_PORT", label: "SMTP port", required: true, defaultValue: "587" },
  { key: "MAIL_USERNAME", label: "SMTP username", required: true },
  { key: "MAIL_PASSWORD", label: "SMTP password", required: true },
  {
    key: "MAIL_ENCRYPTION",
    label: "SMTP encryption (tls/ssl)",
    required: true,
    defaultValue: "tls",
  },
  { key: "MAIL_FROM_ADDRESS", label: "From email", required: true },
  {
    key: "MAIL_FROM_NAME",
    label: "From name",
    required: false,
    defaultValue: "Portfolio Contact",
  },
  { key: "MAIL_TO_ADDRESS", label: "Recipient email", required: true },
  {
    key: "MAIL_TO_NAME",
    label: "Recipient name",
    required: false,
    defaultValue: "Portfolio Owner",
  },
];

function parseEnv(contents) {
  const map = new Map();
  for (const rawLine of contents.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (!match) continue;
    const [, key, rest] = match;
    const value = rest.trim().replace(/^['"]|['"]$/g, "");
    map.set(key, value);
  }
  return map;
}

function formatEnvValue(value) {
  if (value.includes(" ") || value.includes("#")) {
    return JSON.stringify(value);
  }
  return value;
}

const fileEnv = fs.existsSync(envPath)
  ? parseEnv(fs.readFileSync(envPath, "utf8"))
  : new Map();

const resolved = new Map();
for (const item of required) {
  const existing = process.env[item.key] ?? fileEnv.get(item.key) ?? "";
  resolved.set(item.key, existing);
}

const missing = required.filter((item) => item.required && !resolved.get(item.key));

if (missing.length === 0) {
  process.exit(0);
}

if (!process.stdin.isTTY) {
  console.error(
    `Missing required mail environment keys: ${missing
      .map((x) => x.key)
      .join(", ")}. Create .env.mail before building.`
  );
  process.exit(1);
}

const rl = readline.createInterface({ input, output });

try {
  console.log("Mail configuration is incomplete. Please enter SMTP settings:");

  for (const item of required) {
    const current = resolved.get(item.key) || item.defaultValue || "";
    const suffix = current ? ` [${current}]` : "";
    const answer = (await rl.question(`${item.label}${suffix}: `)).trim();
    const finalValue = answer || current;

    if (item.required && !finalValue) {
      console.error(`Value for ${item.key} is required.`);
      process.exit(1);
    }

    resolved.set(item.key, finalValue);
  }
} finally {
  rl.close();
}

const header =
  "# Auto-generated by `npm run build` for PHP contact API.\n" +
  "# Do not commit real secrets. Keep this file on the server or local machine only.\n";

const body = required
  .map((item) => `${item.key}=${formatEnvValue(resolved.get(item.key) || "")}`)
  .join("\n");

fs.writeFileSync(envPath, `${header}\n${body}\n`, "utf8");
console.log(`Saved mail config to ${envPath}`);
